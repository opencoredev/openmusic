import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";
import { cancellationReasonV, commandResultV, keyStateV, platformV, providerV, sealedV, storedAnchorV, storedCommandV } from "./model";

export default defineSchema({
  /** One account's sync group: every device signed in to the same Clerk user. One library per user. */
  libraries: defineTable({
    /**
     * The Clerk user: `identity.tokenIdentifier` (issuer and subject). Missing only on libraries from before
     * accounts (paired by invite codes); `legacy:sweep` deletes those with all their rows. Every library created
     * since has it.
     */
    owner: v.optional(v.string()),
    createdAt: v.number(),
    /** Fingerprint of the account's vault key (the key itself never reaches the server). */
    keyId: v.optional(v.string()),
    /**
     * Set when a device that could open the vault left while others still hold the key: a remaining holder must
     * replace the key (`keys:rotate`) before the vault takes new writes or the key is granted again.
     */
    keyRotation: v.optional(v.object({ neededSince: v.number() })),
    /** Fingerprints of keys this account used before (rotated away or reset), never adopted again. Newest last. */
    retiredKeyIds: v.optional(v.array(v.string())),
    /**
     * Grows with every change to the account's key state (the key, its rotation, any device's key row, a device
     * joining or leaving). `devices:list` reports it, so a device can tell an old answer from a newer one and never
     * acts on, or drops what it saved because of, an observation older than one it already applied.
     */
    keyRevision: v.optional(v.number()),
    /**
     * The key the last rotation replaced and until when sealed playback, queues and commands under it are still
     * taken (content.ts, `PREVIOUS_KEY_GRACE_MS`): a holder that hasn't taken the new key yet keeps publishing.
     */
    previousKey: v.optional(v.object({ keyId: v.string(), until: v.number() })),
    /** The library and all its rows are deleted after this (moved forward while any device is seen). */
    expiresAt: v.optional(v.number()),
    /** Legacy (paired libraries only): when a second device first joined. */
    pairedAt: v.optional(v.number()),
    /** Legacy (paired libraries only): SHA-256 of the creating request's `requestId`. */
    createRequestHash: v.optional(v.string()),
  })
    .index("by_owner", ["owner"])
    .index("by_expiresAt", ["expiresAt"]),

  devices: defineTable({
    libraryId: v.id("libraries"),
    name: v.string(),
    platform: platformV,
    model: v.string(),
    appVersion: v.string(),
    /** Hex SHA-256 of the device token (generated by the device at sign-in). The token itself is never stored. */
    tokenHash: v.string(),
    createdAt: v.number(),
    lastSeenAt: v.number(),
  })
    .index("by_tokenHash", ["tokenHash"])
    .index("by_library", ["libraryId"]),

  /**
   * One row per device that published its player: the position anchor in the clear (where and how it plays, never
   * what) and, from a device that holds the vault key, `content`: the current track, its index in the window and the
   * window's length, sealed (kind `playback`). A device without the key publishes no content.
   */
  playback: defineTable({
    libraryId: v.id("libraries"),
    deviceId: v.id("devices"),
    content: v.optional(sealedV),
    /** Bumped whenever the content (and the queue window with it) is replaced or dropped, so readers refetch the queue. */
    queueVersion: v.number(),
    anchor: storedAnchorV,
    updatedAt: v.number(),
  })
    .index("by_device", ["deviceId"])
    .index("by_library", ["libraryId"]),

  /** The queue window of a device (up to 20 entries before the current one and 100 after), sealed (kind `queue`). */
  queues: defineTable({
    libraryId: v.id("libraries"),
    deviceId: v.id("devices"),
    content: sealedV,
    version: v.number(),
  }).index("by_device", ["deviceId"]),

  commands: defineTable({
    libraryId: v.id("libraries"),
    fromDeviceId: v.id("devices"),
    toDeviceId: v.id("devices"),
    command: storedCommandV,
    createdAt: v.number(),
    expiresAt: v.number(),
    ackedAt: v.optional(v.number()),
    result: v.optional(commandResultV),
    /** The sender's id for this command, so a retried send (socket, then HTTP) is stored once. */
    clientId: v.optional(v.string()),
  })
    .index("by_to_pending", ["toDeviceId", "ackedAt", "createdAt"])
    .index("by_from", ["fromDeviceId", "createdAt"])
    .index("by_from_clientId", ["fromDeviceId", "clientId"])
    .index("by_expiresAt", ["expiresAt"]),

  /**
   * Each device's X25519 public key and whether it holds the vault key. One row per device registered since
   * accounts (devices of legacy libraries have none).
   */
  deviceKeys: defineTable({
    libraryId: v.id("libraries"),
    deviceId: v.id("devices"),
    /** base64 of the 32-byte X25519 public key. Holders wrap the vault key to it. */
    publicKey: v.string(),
    state: keyStateV,
    /**
     * The newest vault key fingerprint this device was ever given: made, granted, or wrapped to it by a rotation.
     * It stays when the state moves back to `requested` (a device that unwrapped a grant can ask again), so a device
     * that may have the current key always forces a rotation when it leaves. Missing on rows from before it existed,
     * where the state alone decides.
     */
    exposedKeyId: v.optional(v.string()),
    updatedAt: v.number(),
  })
    .index("by_device", ["deviceId"])
    .index("by_library", ["libraryId"]),

  /**
   * Device tokens that may never register again, with the user they are refused for. A device token is single-use:
   * once its device is gone, `account:register` refuses it for that user, so a copy of a registration still on its
   * way (a retry over HTTP, a replay on a new socket) can never create a device with a token and key the device
   * already discarded. Two reasons:
   * - `retired`: the token's device was removed (signed out, removed from another device, evicted, its account
   *   expired). Recorded by every path that deletes a device, in the same transaction, always: bounded by how many
   *   devices a user can register.
   * - `withdrawn`: a registration a device withdrew before learning whether it landed (`account:unregister` with a
   *   token no device of the user's has). Rate limited and capped per user (`LIMITS.withdrawals*`).
   * Kept for `LIMITS.cancelledRegistrationTtlMs`.
   *
   * `reason` is optional for now: a deployment may hold rows from before it existed, and a required field would make
   * the schema push fail on them. A row without one counts as `withdrawn` everywhere (the per-user cap included,
   * `withdrawalsOf` in account.ts). Deploy order: push this schema, run `account:backfillCancellationReasons`, and only then make `reason`
   * required in a later change (docs/accounts-design.md, "Data model changes").
   */
  cancelledRegistrations: defineTable({
    tokenHash: v.string(),
    owner: v.string(),
    reason: v.optional(cancellationReasonV),
    createdAt: v.number(),
    expiresAt: v.number(),
  })
    .index("by_tokenHash_owner", ["tokenHash", "owner"])
    .index("by_owner_reason_expiresAt", ["owner", "reason", "expiresAt"])
    .index("by_expiresAt", ["expiresAt"]),

  /** Legacy: invite codes from before accounts. Kept so old rows validate; `legacy:sweep` empties it. */
  invites: defineTable({
    libraryId: v.id("libraries"),
    createdBy: v.id("devices"),
    codeHash: v.string(),
    createdAt: v.number(),
    expiresAt: v.number(),
    redeemedAt: v.optional(v.number()),
    redeemedBy: v.optional(v.id("devices")),
    redeemRequestHash: v.optional(v.string()),
    retries: v.optional(v.number()),
    purgeAt: v.optional(v.number()),
  }),

  /**
   * End-to-end sealed provider sign-ins, one row per library and provider. `sealed` is AES-GCM ciphertext
   * (base64) under the account's vault key, which only devices hold. A row without `sealed` is a tombstone left by
   * "sign out everywhere". `revision` counts every write (sign-ins and tombstones) and is bound into the
   * ciphertext's authenticated data, so an old blob can't be replayed at a newer revision. Missing on rows written
   * before revisions existed (read as 0). A row with `cleared` has no sign-in either but isn't a sign-out: the
   * account lost its vault key (no device that could open it was left), and the row keeps the revision count so
   * that no device's record of what it applied ever runs ahead of the server.
   */
  vault: defineTable({
    libraryId: v.id("libraries"),
    provider: providerV,
    sealed: v.optional(v.string()),
    cleared: v.optional(v.boolean()),
    keyId: v.string(),
    revision: v.optional(v.number()),
    updatedAt: v.number(),
    updatedBy: v.id("devices"),
  }).index("by_library_provider", ["libraryId", "provider"]),

  /**
   * Synced settings (playback preferences, recent searches), last write wins per key. The key and the times are in
   * the clear; `value` is the JSON text sealed under the vault key (kind `setting`, the key bound in), always under the
   * library's current key: a rotation re-seals every row in the same transaction, and a reset deletes them.
   */
  settings: defineTable({
    libraryId: v.id("libraries"),
    key: v.string(),
    value: sealedV,
    updatedAt: v.number(),
    updatedBy: v.id("devices"),
    /** The writer's id for this write, so a retried put of the same write doesn't count as a new one. */
    writeId: v.optional(v.string()),
  }).index("by_library_key", ["libraryId", "key"]),

  /**
   * Recent settings writes by `writeId`, kept for `LIMITS.settingOpTtlMs`. A retry of a write that already landed
   * (socket, then HTTP) finds its operation here and changes nothing, even after another device wrote the key since.
   */
  settingOps: defineTable({
    libraryId: v.id("libraries"),
    key: v.string(),
    writeId: v.string(),
    deviceId: v.id("devices"),
    /** `updatedAt` the write got (or, for a fill-in that found a value, the stored value's). */
    updatedAt: v.number(),
    expiresAt: v.number(),
  })
    .index("by_library_key_write", ["libraryId", "key", "writeId"])
    .index("by_expiresAt", ["expiresAt"]),

  /**
   * Rate-limit counters (see `throttle.ts`). `key` names the limit and its subject, for example
   * "register:<hash of the user>". Rows are swept once `expiresAt` passes.
   */
  throttles: defineTable({
    key: v.string(),
    windowStart: v.number(),
    count: v.number(),
    /** Exponential lockout for client keys. */
    blockedUntil: v.optional(v.number()),
    expiresAt: v.number(),
  })
    .index("by_key", ["key", "windowStart"])
    .index("by_expiresAt", ["expiresAt"]),

  /** Legacy: the old fixed-window redeem counters. Kept so existing rows validate; `legacy:sweep` empties it. */
  redeemFailures: defineTable({
    key: v.string(),
    windowStart: v.number(),
    count: v.number(),
  }),
});
