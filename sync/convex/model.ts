// Shared validators and limits for the OpenMusic sync backend. The wire shapes mirror the Swift `Codable`
// types in Sources/OpenMusicSync/Wire.swift; docs/sync-design.md is the contract between them.
import { v, type Infer } from "convex/values";

export const LIMITS = {
  /** A device counts as online when it was seen within this window. */
  onlineWindowMs: 90_000,
  commandTtlMs: 2 * 60_000,
  /** Queue window around the current entry. */
  queueBefore: 20,
  queueAfter: 100,
  maxNameLength: 64,
  maxShortString: 256,
  maxSealedBytes: 64 * 1024,
  maxSettingKeys: 64,
  /** Device tokens are generated by the device: 32 random bytes, base64url (43 characters). */
  minTokenLength: 32,
  maxTokenLength: 100,
  /** A wrapped vault key: 32-byte ephemeral public key + 12-byte nonce + 32-byte key + 16-byte tag, base64. */
  maxWrappedKeyLength: 512,
  /** Rows one sweep run deletes per table before it schedules another run. */
  sweepBatch: 500,
  /**
   * Rows one run of the owner-less library sweep deletes in all, descendants included, before it schedules another
   * run. Far below Convex's per-transaction limits, so one run never fails however big a library is.
   */
  librarySweepRows: 1000,
  /** `keys:request` calls per device per hour: each one makes a holder show a prompt. */
  keyRequestsPerDeviceHour: 20,
  /** Retired vault key fingerprints a library remembers, so an old key is never adopted again. */
  maxRetiredKeys: 16,
  /** How long a settings write's `writeId` is remembered, so a late retry of it can't overwrite a newer value. */
  settingOpTtlMs: 10 * 60_000,
  /**
   * How long a retired or withdrawn device token stays refused (`cancelledRegistrations`). Far longer than any copy of
   * a registration can be on its way: a mutation times out after 30 s, and a device stops sending a registration once
   * it settled (credentials saved) or was withdrawn.
   */
  cancelledRegistrationTtlMs: 30 * 24 * 3600_000,
  /**
   * The oldest registration attempt `account:register` takes (by the `createdAt` the device made it with and sends with
   * every attempt): far inside `cancelledRegistrationTtlMs`, so an attempt resent after its token's retirement was
   * forgotten is refused instead of registering that token again. Devices stop resending after 7 days themselves.
   */
  registrationMaxAgeMs: 14 * 24 * 3600_000,
  /** How far ahead of the server's clock a registration's `createdAt` may be (a device clock running fast). */
  registrationMaxAheadMs: 24 * 3600_000,
  /**
   * New withdrawals (`account:unregister` of a token no device of the user's has) per user per hour. A retry of one
   * already recorded is free; removing a real device is never limited.
   */
  withdrawalsPerUserPerHour: 10,
  /** Withdrawals one user can have recorded at once (each kept `cancelledRegistrationTtlMs`). */
  maxWithdrawalsPerUser: 50,
  /** Device registrations per user per hour (`account:register`; retries of one registration don't count). */
  registerPerUserPerHour: 30,
  /** Devices per account. Registering one more removes the device seen least recently. */
  maxDevicesPerLibrary: 32,
  /** An account's sync data is deleted after this long without any of its devices being seen. */
  libraryIdleTtlMs: 60 * 24 * 3600_000,
  /** Heartbeats move a library's expiry forward at most this often. */
  libraryRefreshMs: 3600_000,
  /** How many recent commands `commands:outgoing` returns. */
  outgoingLimit: 20,
} as const;

/**
 * Why a device token is refused (`cancelledRegistrations.reason`). Rows written before the field existed have none and
 * count as `withdrawn` until `account:backfillCancellationReasons` fills it in.
 */
export const cancellationReasonV = v.union(v.literal("retired"), v.literal("withdrawn"));
export type CancellationReason = Infer<typeof cancellationReasonV>;

/** Every platform an OpenMusic app exists or is planned for. Clients show an unknown one as a generic computer. */
export const platformV = v.union(v.literal("mac"), v.literal("ios"), v.literal("windows"), v.literal("android"), v.literal("linux"));
export type Platform = Infer<typeof platformV>;

/**
 * One run of the verification exchange between a device that asks for the vault key and a holder (see
 * docs/accounts-design.md, "Approving a device"). Every field is public: commitments, nonces and public keys. The
 * asking device commits to its nonce first, a holder answers with its own nonce, and only then does the asking
 * device reveal its nonce, so neither side (nor the server between them) can steer the code both devices show.
 */
export const exchangeV = v.union(
  /** The asking device published `commitment` = SHA-256 of its public key and a secret nonce. */
  v.object({ phase: v.literal("committed"), commitment: v.string(), at: v.number() }),
  /** A holder answered: its device public key and a fresh nonce, chosen after it saw the commitment. */
  v.object({
    phase: v.literal("answered"),
    commitment: v.string(),
    at: v.number(),
    holder: v.id("devices"),
    holderKey: v.string(),
    holderNonce: v.string(),
  }),
  /** The asking device revealed its nonce. Both devices can now show the code. */
  v.object({
    phase: v.literal("revealed"),
    commitment: v.string(),
    at: v.number(),
    holder: v.id("devices"),
    holderKey: v.string(),
    holderNonce: v.string(),
    nonce: v.string(),
  }),
);
export type Exchange = Infer<typeof exchangeV>;

/** A new vault key from a rotation, wrapped to one holder; waits on the holder's row until it takes it. */
export const rekeyV = v.object({
  keyId: v.string(),
  /** The key it replaces. Opening the wrap needs it, so only a holder of that key could have made the wrap. */
  fromKeyId: v.string(),
  wrapped: v.string(),
  by: v.id("devices"),
});

/**
 * Whether a device holds the account's vault key (the AES key the YouTube Music and Spotify sign-ins are sealed
 * with). See docs/accounts-design.md, "Sign-in vault key".
 */
export const keyStateV = v.union(
  /** Has the key: made it, or accepted a grant. `rekey` carries a rotated key it hasn't taken yet. */
  v.object({ kind: v.literal("holder"), since: v.number(), rekey: v.optional(rekeyV) }),
  /**
   * Has no key and asks for it. Without `exchange` it hasn't committed to a nonce yet (it does at once); rows
   * written before the exchange existed have none either.
   */
  v.object({ kind: v.literal("requested"), requestedAt: v.number(), exchange: v.optional(exchangeV) }),
  /** A holder said no. No prompts until the device asks again (`keys:request`). */
  v.object({ kind: v.literal("denied"), deniedAt: v.number(), deniedBy: v.id("devices") }),
  /** A holder wrapped the key to this device after the exchange; the device hasn't confirmed yet (`keys:accept`). */
  v.object({
    kind: v.literal("granted"),
    grantedAt: v.number(),
    grantedBy: v.id("devices"),
    keyId: v.string(),
    /** The vault key, sealed under a key only the granting holder and this device can derive. */
    wrapped: v.string(),
    /** The exchange the grant belongs to (missing on grants from before the exchange, which can't be opened). */
    commitment: v.optional(v.string()),
  }),
);
export type KeyState = Infer<typeof keyStateV>;
export const keyStateKindV = v.union(v.literal("holder"), v.literal("requested"), v.literal("denied"), v.literal("granted"));

export const deviceInfoV = v.object({
  name: v.string(),
  platform: platformV,
  model: v.string(),
  appVersion: v.string(),
});
export type DeviceInfo = Infer<typeof deviceInfoV>;

export const providerV = v.union(v.literal("youtubeMusic"), v.literal("spotify"));

/**
 * One sealed field: `{ v: 1, keyId, sealed }`, `sealed` being base64 of AES-GCM nonce ‖ ciphertext ‖ tag under a key
 * derived from the account's vault key. What it holds (a track, a queue, a setting) is never readable here: see
 * content.ts and docs/sync-design.md, "What the server can see".
 */
export const sealedV = v.object({ v: v.literal(1), keyId: v.string(), sealed: v.string() });
export type Sealed = Infer<typeof sealedV>;

export const repeatV = v.union(v.literal("off"), v.literal("all"), v.literal("one"));

/**
 * The position anchor: live position = positionMs + (serverNow - positionAt) * rate while playing. It says where and
 * how something plays, never what: it stays readable so a device without the key can show "Playing on Riley's Mac ·
 * 2:13" and control it.
 */
export const anchorV = v.object({
  positionMs: v.number(),
  /** Server clock (ms) at which `positionMs` was true. Optional on input: the server stamps it. */
  positionAt: v.optional(v.number()),
  isPlaying: v.boolean(),
  rate: v.number(),
  durationMs: v.optional(v.number()),
  volume: v.number(),
  shuffle: v.boolean(),
  repeat: repeatV,
});
export type AnchorInput = Infer<typeof anchorV>;

/** An anchor as stored and returned: `positionAt` is always set. */
export const storedAnchorV = v.object({
  positionMs: v.number(),
  positionAt: v.number(),
  isPlaying: v.boolean(),
  rate: v.number(),
  durationMs: v.optional(v.number()),
  volume: v.number(),
  shuffle: v.boolean(),
  repeat: repeatV,
});

function commandUnion<A extends typeof anchorV | typeof storedAnchorV>(anchor: A) {
  return v.union(
    v.object({ kind: v.literal("play") }),
    v.object({ kind: v.literal("pause") }),
    v.object({ kind: v.literal("toggle") }),
    v.object({ kind: v.literal("next") }),
    v.object({ kind: v.literal("previous") }),
    v.object({ kind: v.literal("stop") }),
    v.object({ kind: v.literal("seek"), positionMs: v.number() }),
    v.object({ kind: v.literal("setVolume"), volume: v.number() }),
    /** Move playback to the target: the anchor in the clear, the queue window and its index sealed (kind `command`). */
    v.object({ kind: v.literal("takeOver"), anchor, content: sealedV }),
  );
}

/** A command as a device sends it. */
export const commandV = commandUnion(anchorV);
export type Command = Infer<typeof commandV>;
/** A command as stored and delivered (a takeover's anchor stamped by the server). */
export const storedCommandV = commandUnion(storedAnchorV);
export type StoredCommand = Infer<typeof storedCommandV>;

/**
 * Why a command failed, as a code from a fixed list: the only failure detail the server sees. A free-text message
 * (it may name a song) travels sealed (`content`, kind `result`), and only from a device that holds the key.
 */
export const failureReasonV = v.union(
  v.literal("expired"),
  v.literal("unavailable"),
  v.literal("nothingToPlay"),
  v.literal("needsKey"),
  v.literal("unreadable"),
  v.literal("providerUnavailable"),
  v.literal("playbackFailed"),
  v.literal("failed"),
);
export const commandResultV = v.object({ ok: v.boolean(), reason: v.optional(failureReasonV), content: v.optional(sealedV) });
export type CommandResult = Infer<typeof commandResultV>;

/** Every mutation result carries the server clock so clients can keep their offset. */
export const serverNowV = v.number();
